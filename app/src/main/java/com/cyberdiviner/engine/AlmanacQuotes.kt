    /**
     * Get the quote for a specific day of year (1-365).
     * Deterministic based on the day index.
     */
    fun getQuote(dayOfYear: Int): DailyQuote {
        val index = (dayOfYear - 1).coerceIn(0, 364)
        return QUOTES[index]
    }

    /**
     * Get the quote for a specific date.
     */
    fun getQuoteForDate(date: java.time.LocalDate): DailyQuote {
        return getQuote(date.dayOfYear)
    }

