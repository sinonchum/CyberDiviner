 * AlmanacQuotes — 赛博黄历每日签语
 *
 * 365 unique philosophical quotes in cyberpunk + Chinese philosophy style.
 * Each quote includes:
 *   - text: the main quote (签语)
 *   - luckyAction: 宜 (auspicious activity)
 *   - unluckyAction: 忌 (inauspicious activity)
